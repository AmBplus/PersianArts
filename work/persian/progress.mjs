#!/usr/bin/env node
// Builds the tracked progress record of the Persian shotcraft localization from the (git-ignored) per-card outputs.
//   - copies work/persian/out/<slug>/{report,review}.json -> work/persian/reports/<slug>.{report,review}.json (tracked)
//   - writes work/persian/progress.json and work/persian/PROGRESS.md (tracked)
// Status per card:
//   todo        nothing produced yet
//   localized   author report exists, not reviewed yet (or review failed)
//   approved    independent review approved (only minor issues)
//   fixed       review asked for fixes and the report was rewritten after the review
//   needs-fix   review asked for fixes, no fix recorded yet
// Usage (repo root): node work/persian/progress.mjs
import {readFile, writeFile, mkdir, stat, copyFile, readdir} from "node:fs/promises";
import {spawnSync} from "node:child_process";
import {resolve, join} from "node:path";

const root = resolve("work/persian");
const reports = join(root, "reports");
await mkdir(reports, {recursive: true});
const slugs = JSON.parse(spawnSync(process.execPath, [join(root, "card-info.mjs"), "--list"], {encoding: "utf8"}).stdout);
const st = (p) => stat(p).then((s) => s, () => null);
const json = async (p) => { try { return JSON.parse(await readFile(p, "utf8")); } catch { return null; } };

const rows = [];
for (const slug of slugs) {
  const out = join(root, "out", slug);
  const rp = join(out, "report.json"), vp = join(out, "review.json");
  const [rs, vs] = [await st(rp), await st(vp)];
  if (rs) await copyFile(rp, join(reports, `${slug}.report.json`));
  if (vs) await copyFile(vp, join(reports, `${slug}.review.json`));
  // fall back to the tracked copy when the local out dir is missing (fresh clone on another machine)
  const report = rs ? await json(rp) : await json(join(reports, `${slug}.report.json`));
  const review = vs ? await json(vp) : await json(join(reports, `${slug}.review.json`));
  const videos = (await readdir(out).catch(() => [])).filter((f) => f.endsWith(".fa.mp4")).length;
  const majors = (review?.issues || []).filter((i) => i.severity !== "minor").length;
  let status = "todo";
  if (report || videos) status = "localized";
  if (review) {
    if (review.verdict === "approve" && !majors) status = "approved";
    else status = report?.fixedAfterReview || (rs && vs && rs.mtimeMs > vs.mtimeMs) ? "fixed" : "needs-fix";
  }
  const font = report?.font?.family || report?.font || "";
  rows.push({slug, status, font: typeof font === "string" ? font : JSON.stringify(font), videos, majors, concerns: (report?.concerns || []).length});
}

const count = (s) => rows.filter((r) => r.status === s).length;
const summary = {todo: count("todo"), localized: count("localized"), approved: count("approved"), fixed: count("fixed"), "needs-fix": count("needs-fix"), total: rows.length};
await writeFile(join(root, "progress.json"), JSON.stringify({generatedAt: new Date().toISOString(), summary, cards: rows}, null, 1));
const md = [
  "# Persian shotcraft localization — progress",
  "",
  `Generated by \`node work/persian/progress.mjs\` at ${new Date().toISOString()}. Do not edit by hand.`,
  "",
  `**${summary.approved + summary.fixed} / ${summary.total} done** (approved ${summary.approved}, fixed ${summary.fixed}) · localized awaiting review ${summary.localized} · needs-fix ${summary["needs-fix"]} · todo ${summary.todo}`,
  "",
  "| card | status | font | videos | open majors |",
  "|---|---|---|---|---|",
  ...rows.map((r) => `| ${r.slug} | ${r.status} | ${r.font} | ${r.videos} | ${r.majors} |`),
  "",
].join("\n");
await writeFile(join(root, "PROGRESS.md"), md);
console.log(JSON.stringify(summary));
